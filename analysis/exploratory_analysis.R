library(arrow)
library(dplyr)
library(ggplot2)
master <- read_parquet('data/processed/flights_master.parquet')
predictive <- read_parquet('data/processed/flights_predictive.parquet')
explanatory <- read_parquet('data/processed/flights_explanatory.parquet')
print(sapply(list(predictive=predictive, explanatory=explanatory), nrow))
print(sapply(predictive, function(x) mean(is.na(x))))
print(sapply(explanatory, function(x) mean(is.na(x))))
print(explanatory |> group_by(Reporting_Airline) |> summarise(n=n(), mean_delay=mean(departure_delay_minutes,na.rm=TRUE), median_delay=median(departure_delay_minutes,na.rm=TRUE)))
print(explanatory |> group_by(Origin) |> summarise(n=n(), mean_delay=mean(departure_delay_minutes,na.rm=TRUE)))
print(ggplot(explanatory, aes(departure_delay_minutes)) + geom_histogram(binwidth=10) + coord_cartesian(xlim=c(-60,300)))
print(ggplot(explanatory, aes(as.integer(as.numeric(CRSDepTime)/100), departure_delay_minutes)) + stat_summary(fun=mean, geom='line'))
print(ggplot(explanatory, aes(departure_origin_wind_speed_kt, departure_delay_minutes)) + geom_point(alpha=.1) + coord_cartesian(ylim=c(-60,300)))
print(ggplot(explanatory, aes(previous_flight_arrival_delay_minutes, departure_delay_minutes)) + geom_point(alpha=.1) + coord_cartesian(xlim=c(-60,300), ylim=c(-60,300)))
